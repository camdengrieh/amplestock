"""Transports: one real (urllib), one that replays a recorded fixture cassette.

Every collector in this package reaches the network through a `Transport`, never through `urllib`
directly. That is what makes the whole pipeline runnable — and unit-testable — with no egress: the
`--fixtures` run swaps `HttpTransport` for `FixtureTransport` and nothing else changes.

The fixture cassette is a single JSON file (`fixtures/cassette.json`) holding:

* `chain` — head block, head timestamp and block time, from which block headers are synthesised;
* `text` / `json` — recorded HTTP bodies keyed by URL;
* `logs` — a flat list of `eth_getLogs` results, filtered by range/address/topics on replay;
* `calls` — `eth_call` return data keyed by `<to>:<calldata>`;
* `storage` — `eth_getStorageAt` values keyed by `<address>:<slot>`.

**The committed cassette is synthetic.** It is generated by `tools/generate_fixtures.py` from a
seeded PRNG and contains no market data; see that file and the `$comment` in the cassette.
"""

from __future__ import annotations

import gzip
import json
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

DEFAULT_TIMEOUT = 30.0
DEFAULT_RETRIES = 3
USER_AGENT = "amplestocks-quant/constituents (+https://github.com/amplestocks)"


class TransportError(RuntimeError):
    """A request failed after every retry, or the fixture cassette has no answer for it."""


class Transport(Protocol):
    """The surface every collector is allowed to use."""

    def get_json(self, url: str, *, headers: dict[str, str] | None = None) -> Any:
        """GET `url` and parse the body as JSON."""

    def get_text(self, url: str, *, headers: dict[str, str] | None = None) -> str:
        """GET `url` and return the body as text."""

    def post_json(self, url: str, payload: Any, *, headers: dict[str, str] | None = None) -> Any:
        """POST `payload` as JSON to `url` and parse the response as JSON."""


# ------------------------------------------------------------------------------------------------
# Real transport
# ------------------------------------------------------------------------------------------------


@dataclass
class HttpTransport:
    """`urllib`-backed transport with retries and exponential backoff.

    Deliberately dependency-free: a launch-set run has to work from a clean `python3` on an
    operator's laptop, and adding `requests`/`httpx` to `pyproject.toml` for six GETs is not worth
    the supply-chain surface.
    """

    timeout: float = DEFAULT_TIMEOUT
    retries: int = DEFAULT_RETRIES
    backoff: float = 0.75
    #: Every URL this transport has touched, in order — copied into the report's provenance block.
    calls: list[str] = field(default_factory=list)

    def _request(self, url: str, data: bytes | None, headers: dict[str, str] | None) -> bytes:
        merged = {
            "User-Agent": USER_AGENT,
            "Accept": "application/json, text/html;q=0.9, */*;q=0.5",
            "Accept-Encoding": "gzip, identity",
        }
        if data is not None:
            merged["Content-Type"] = "application/json"
        merged.update(headers or {})
        self.calls.append(url)

        last: Exception | None = None
        for attempt in range(self.retries):
            request = urllib.request.Request(url, data=data, headers=merged)
            try:
                with urllib.request.urlopen(request, timeout=self.timeout) as response:
                    body = response.read()
                    if response.headers.get("Content-Encoding") == "gzip":
                        body = gzip.decompress(body)
                    return body
            except urllib.error.HTTPError as exc:
                last = exc
                if exc.code in (400, 401, 403, 404, 405, 410):
                    break
            except (urllib.error.URLError, TimeoutError, OSError) as exc:
                last = exc
            if attempt + 1 < self.retries:
                time.sleep(self.backoff * (2**attempt))
        raise TransportError(f"{url}: {last}") from last

    def get_json(self, url: str, *, headers: dict[str, str] | None = None) -> Any:
        """GET `url` and parse the body as JSON."""
        return json.loads(self._request(url, None, headers))

    def get_text(self, url: str, *, headers: dict[str, str] | None = None) -> str:
        """GET `url` and return the body as text."""
        return self._request(url, None, headers).decode("utf-8", "replace")

    def post_json(self, url: str, payload: Any, *, headers: dict[str, str] | None = None) -> Any:
        """POST `payload` as JSON to `url` and parse the response as JSON."""
        body = json.dumps(payload).encode()
        return json.loads(self._request(url, body, headers))


