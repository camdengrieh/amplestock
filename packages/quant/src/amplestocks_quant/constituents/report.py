def _provenance(add, result: RunResult) -> None:
    params = result.params
    add("## 1. What this run measured")
    add("")
    add("| | |")
    add("|---|---|")
    add(f"| Data timestamp (head block time) | {result.iso()} |")
    add(f"| Report generated | {result.iso(result.generated_at)} |")
    add("| Chain | Robinhood Chain 4663 |")
    add(
        f"| Window | {params.window_days} days (`V30`), {params.short_window_days} days (`V7`); "
        f"blocks {result.window_from_block:,} → {result.head_block:,} |"
    )
    add(f"| Tokens measured | {len(result.metrics)} |")
    add(f"| Pools measured | {sum(len(m.markets) for m in result.metrics)} |")
    add(f"| Placement `P` | ${params.placement:,.0f} (also computed at " + ", ".join(f"${p:,.0f}" for p in params.placements[1:]) + ") |")
    add(f"| Fee basis for ranking | `{params.fee_basis}` |")
    add(f"| RPC requests | {result.rpc_requests:,} ({result.log_requests:,} `eth_getLogs`) |")
    add(f"| Mode | {'FIXTURE (no network)' if result.is_fixture else 'live chain read'} |")
