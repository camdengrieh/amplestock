FLAG_LEGEND = {
    "high_volume": "top-quartile 30-day volume",
    "thin_liquidity": "top-quartile turnover (V30/L)",
    "dead": "no 7-day volume, or depth below the floor",
    "no_feed": "no Standard Chainlink feed",
    "multiplier": "uiMultiplier() != 1 (corporate action in effect)",
    "insufficient_history": "too few daily prices for a volatility estimate",
    "unpriced": "no USD price could be derived",
    "api_delta": "chain volume disagrees with the aggregators by >40%",
}


def usd(value: float | None) -> str:
    """Compact USD."""
    if value is None:
        return "-"
    if value >= 1_000_000_000:
        return f"${value / 1e9:.2f}B"
    if value >= 1_000_000:
        return f"${value / 1e6:.2f}M"
    if value >= 1_000:
        return f"${value / 1e3:.1f}k"
    if value <= 0:
        return "$0"
    return f"${value:,.2f}" if value < 10 else f"${value:,.0f}"


def pct(value: float | None, digits: int = 2) -> str:
    """Percentage from a ratio, without `-0%`."""
    if value is None:
        return "-"
    scaled = value * 100
    if abs(scaled) < 0.5 * 10**-digits:
        scaled = 0.0
    return f"{scaled:.{digits}f}%"


def share_pct(value: float | None) -> str:
    """Capturable share, which spans four orders of magnitude across a real universe."""
    if value is None:
        return "-"
    scaled = value * 100
    if scaled >= 1:
        return f"{scaled:.2f}%"
    if scaled >= 0.01:
        return f"{scaled:.3f}%"
    return f"{scaled:.4f}%"


def _flags(record: TokenMetrics) -> str:
    return ", ".join(sorted(record.flags)) or "-"


def _feed_cell(record: TokenMetrics) -> str:
    feed = record.feed
    if feed is None:
        return "none"
    heartbeat = f"{feed.heartbeat_seconds}s" if feed.heartbeat_seconds else "?"
    return f"`{feed.proxy[:10]}…` / {heartbeat}"


def render(result: RunResult) -> str:
    """The full report."""
    lines: list[str] = []
    add = lines.append

    add("# Amplestocks launch constituents")
    add("")
    if result.is_fixture:
        add(f"> **{FIXTURE_BANNER}.**")
        add(">")
        add(
            "> This document was produced by the `--fixtures` run, which replays a synthetic "
            "cassette generated by `packages/quant/tools/generate_fixtures.py`. Every ticker, "
            "address, price and volume below is invented to exercise the pipeline. It exists so "
            "the shape of the real output — and the reasoning that produces it — can be reviewed "
            "before the hosts in §10 are reachable. **Do not deploy anything from this file.**"
        )
        add(">")
        add(
            f"> The cassette holds {len(result.metrics)} synthetic tokens, so the recorded run "
            f"selects {result.params.count} rather than 30. The real run takes the default "
            "`--count 30` against the ~90-name Robinhood Stock Token universe; nothing else about "
            "the command changes."
        )
        add("")
    add(
        "How the 30 launch spokes are chosen: rank every Robinhood Stock Token by the fee revenue "
        "Amplestocks' protocol-owned liquidity would earn per dollar placed, drop what cannot be "
        "registered, and keep enough deep names to make rotation work."
    )
    add("")
    _provenance(add, result)
    _methodology(add, result)
    _chosen(add, result)
    _ranking(add, result)
    _placements(add, result)
    _rejected(add, result)
    _inclusion(add, result)
    _crosscheck(add, result)
    _caveats(add, result)
    _sources(add, result)
    _rerun(add, result)
    return "\n".join(lines) + "\n"


